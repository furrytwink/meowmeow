	function Remote.asset(rel)
		local hit = ids[rel];

		if hit then return hit end;
		awaitPacks(rel);
		hit = ids[rel];
		if hit then return hit end;

		if not Remote.current() or (retryAfter[rel] or 0) > os.clock() then return nil end;
		if assetBusy[rel] then
			local deadline = os.clock() + 15;
			repeat task.wait(0.03) until not assetBusy[rel] or not Remote.current() or os.clock() >= deadline;
			return ids[rel];
		end;
		assetBusy[rel] = true;
		local ok, result = pcall(function()
		local body = pendingAssets[rel] or fetch(rel);
		local url = body and adopt(rel, body) or nil;

		settle();

		if url then pendingAssets[rel] = nil else ids[rel] = nil; retryAfter[rel] = os.clock() + 15 end;

		return url;
		end);
		assetBusy[rel] = nil;
		if not ok then Remote.Status.lastIssue = tostring(result); retryAfter[rel] = os.clock() + 15; return nil end;
		return result;
	end;

	function Remote.body(rel)
		local hit = bodies[rel];

		if hit then return hit end;
		awaitPacks(rel);
		hit = bodies[rel];
		if hit then return hit end;

		local bundled = pendingAssets[rel];
		if bundled then
			bodies[rel] = bundled;
			pendingAssets[rel] = nil;
			return bundled;
		end;

		bodies[rel] = fetch(rel);

		return bodies[rel] or nil;
	end;

	function Remote.ensure(rel)
		if isData(rel) then return Remote.body(rel) ~= nil end;

		return Remote.asset(rel) ~= nil;
	end;

	function Remote.repair(rel)
		ids[rel], bodies[rel] = nil, nil;
		retryAfter[rel] = nil;
		for path, relative in pairs(relativePaths) do
			if relative == rel then byPath[path] = nil end;
		end;

		return Remote.ensure(rel);
	end;

	function Remote.id(path)
		local hit = byPath[path];

		if hit ~= nil then return hit or nil end;
		local relative = relativePaths[path];
		if relative then return Remote.asset(relative) end;

		if type(custom) ~= "function" or type(isfile) ~= "function" then return nil end;
		local exists, found = Remote.io(function() return isfile(path) end);
		if not exists or not found then return nil end;

		local ok, url = Remote.invoke(function() return custom(path) end, 3);

		byPath[path] = (ok and type(url) == "string" and url ~= "") and url or nil;

		return byPath[path] or nil;
	end;

	function Remote.have(path)
