function Remote.bootstrap()
	if Remote.base == "" then return end;
	local started = os.clock();
	Remote.Status.stage = "fetching";
	pcall(Remote.purge);

	local failed, pending = 0, 0;
	for _, pack in ipairs({ "bundle.pack", "sky.pack" }) do
		pending += 1;
		task.spawn(function()
			local ok, _, missing = pcall(Remote.sync, pack);
			if not ok or (missing or 0) > 0 then
				failed += 1;
				warn("[visuals] " .. pack .. " unavailable; files will be fetched one by one");
			end;
			pending -= 1;
		end);
	end;
	while pending > 0 and Remote.current() do task.wait(0.1) end;

	Remote.Status.failed = failed;
	Remote.Status.stage = failed == 0 and "ready" or "failed";
	if failed > 0 then Remote.Status.lastIssue = "asset pack unavailable; individual downloads remain available" end;
	if Remote.current() then Remote.registerAll() end;
	Remote.Status.elapsed = os.clock() - started;
end;

