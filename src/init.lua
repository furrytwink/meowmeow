				a, b = clipViewport(a,b,viewport);
				if a then segments[#segments + 1] = {a,b} end;
			end;
		end;
		if projected == 0 or maxX < 0 or minX > viewport.X or maxY < 0 or minY > viewport.Y then return nil end;
		minX, minY = math.max(minX,0), math.max(minY,0);
