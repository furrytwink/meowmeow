	end;
	local function clipViewport(a, b, viewport)
		local dx, dy = b.X - a.X, b.Y - a.Y;
		local low, high = 0, 1;
		for _, pair in ipairs({{-dx,a.X},{dx,viewport.X-a.X},{-dy,a.Y},{dy,viewport.Y-a.Y}}) do
			local p, q = pair[1], pair[2];
			if p == 0 then if q < 0 then return nil end;
			else
				local t = q / p;
				if p < 0 then low = math.max(low,t) else high = math.min(high,t) end;
				if low > high then return nil end;
			end;
		end;
		return a:Lerp(b,low), a:Lerp(b,high);
	end;
