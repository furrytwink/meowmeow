	local cache = setmetatable({}, { __mode = "k" });
	function ESP.Visibility.Part(camera, part, target)
		if not (camera and part and part.Parent and part:IsA("BasePart") and target) then return false end;
		local origin, position = camera.CFrame.Position, part.Position;
		local direction = position - origin;
		local distance = direction.Magnitude;
		if distance ~= distance or distance == math.huge then return false end;
		if distance < 0.001 then return true end;
		local now, own = os.clock(), LocalPlayer.Character;
		local saved = cache[part];
		if saved and saved.Target == target and saved.Own == own and saved.Camera == camera
			and now < saved.Expires and (origin - saved.Origin).Magnitude < 0.5
			and (position - saved.Position).Magnitude < 0.5 then return saved.Visible end;
		local params = saved and saved.Params or RaycastParams.new();
		params.FilterType = Enum.RaycastFilterType.Exclude;
		params.IgnoreWater = true;
		local ignored = { target };
		if own and own ~= target then ignored[#ignored + 1] = own end;
		local visible = false;

		for _ = 1, 8 do
			params.FilterDescendantsInstances = ignored;
			local ok, hit = pcall(workspace.Raycast, workspace, origin, direction, params);
			if not ok then break end;
			if not hit then visible = true; break end;
			local object = hit.Instance;
			if object and object:IsA("BasePart") and object.Transparency >= 0.99 then
				ignored[#ignored + 1] = object;
			else break end;
		end;
		cache[part] = { Target = target, Own = own, Camera = camera, Origin = origin,
			Position = position, Expires = now + 0.08, Visible = visible, Params = params };
		return visible;
	end;
