	function ESP.MaterialAlpha(baseTransparency, extraTransparency)
		local alpha = tonumber(extraTransparency) or 0;
		if alpha ~= alpha or alpha == math.huge or alpha == -math.huge then alpha = 0 end;
		alpha = math.clamp(alpha, 0, 1);
		return 1 - (1 - baseTransparency) * (1 - alpha);
	end;
	function ESP.ResolveMaterialStyle(name, extraTransparency)
		local base = MATERIAL_STYLES[name] or MATERIAL_STYLES.ForceField;

		return { material = base.material, reflectance = base.reflectance,
			transparency = ESP.MaterialAlpha(base.transparency, extraTransparency), tint = base.tint, keepTexture = base.keepTexture };
	end;

