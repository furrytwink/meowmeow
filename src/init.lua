		if not state.Enabled or not hl.Enabled then state.Enabled = true; hl.Enabled = true end;
		if state.Fill ~= S.ChamsFill then state.Fill = S.ChamsFill; hl.FillColor = S.ChamsFill end;
		local fillTransparency = S.ChamsFillT / 100;
		if state.FillTransparency ~= fillTransparency then state.FillTransparency = fillTransparency; hl.FillTransparency = fillTransparency end;
		if state.Outline ~= S.ChamsOutline then state.Outline = S.ChamsOutline; hl.OutlineColor = S.ChamsOutline end;
		local outlineTransparency = S.ChamsOutlineT / 100;
		if state.OutlineTransparency ~= outlineTransparency then state.OutlineTransparency = outlineTransparency; hl.OutlineTransparency = outlineTransparency end;
	end;

	local function matChams(player, char, enable)
		if not enable then
			clearChromatic(player);
			clearOcclusion(player);
			dropMaterials(player);
			matClock[player] = nil;
			seenChar[player] = nil;

			return;
		end;
		local tickNow = os.clock();
		if seenChar[player] == char and applied[player] == revision and matClock[player] and tickNow - matClock[player] < 0.15 then return end;

		if painted[player] == char then
			local data = ESP.PaintCache and ESP.PaintCache(char);
			local stale = false;

			if data then
				local seen = 0;

				for part, orig in pairs(data.parts) do
					if part.Parent then
						seen = seen + 1;

						if orig.Wanted and part.Material ~= orig.Wanted then stale = true; break end;
					end;
				end;

				if not stale then
					local live = 0;

					for _, d in ipairs(char:GetDescendants()) do
						if d:IsA("BasePart") then live = live + 1 end;
					end;

					if live ~= seen then stale = true end;
				end;
			end;

			if stale then applied[player] = nil end;
		end;

		if charChanged(player, char) then
			matClock[player] = nil;
			itemClock[player] = nil;

			clearChromatic(player);
			clearOcclusion(player);
			dropMaterials(player);
		end;

		if S.MatType == "Chromatic" then
			local now = os.clock();

			if not matClock[player] or now - matClock[player] >= 0.15 then
				matClock[player] = now;

				clearOcclusion(player);
				dropMaterials(player);
				applyChromatic(player, char, S.MatColor, S.MatStyle, S.MatTransparency);
			end;

			renderChromatic(player);

			return;
		end;

		local now = os.clock();
		if matClock[player] and now - matClock[player] < 0.15 then return end;
		matClock[player] = now;

		clearChromatic(player);

		if S.MatType == "Texture" then

			clearOcclusion(player);

			if painted[player] ~= char then
				if painted[player] then restore(painted[player]) end;
				painted[player], applied[player] = char, nil;
			end;

			if applied[player] ~= revision then
				paint(char, {
					material = nil,
					reflectance = 0,
					transparency = 0,
					tint = true,
					keepTexture = true,
				}, S.MatColor);

				applied[player] = revision;
			end;

			return;
		end;

		if S.MatType == "Flat" then
			dropMaterials(player);
			applyOcclusion(player, char);

			return;
		end;

		clearOcclusion(player);

		if painted[player] ~= char then
			if painted[player] then restore(painted[player]) end;
			painted[player], applied[player] = char, nil;
		end;

		if applied[player] ~= revision then
			paint(char, ESP.ResolveMaterialStyle(S.MatMaterial, S.MatTransparency), S.MatColor);

			applied[player] = revision;
		end;
	end;

