	end;

	function Remote.under(prefix)
		local manifest = Remote.load();
		local out = {};

		if not (manifest and type(manifest.files) == "table") then return out end;

		for rel in pairs(manifest.files) do
			if string.sub(rel, 1, #prefix) == prefix then out[#out + 1] = rel end;
		end;

		table.sort(out);

		return out;
	end;

	function Remote.sync(pack, report)
		if Remote.base == "" then return 0, 0 end;

		local blob = download(Remote.base .. pack, 240);

		if type(blob) ~= "string" or #blob < 8 or string.sub(blob, 1, 4) ~= "SVP1" then
			return 0, 1;
		end;

		local a, b, c, d = string.byte(blob, 5, 8);
		local headLen = a + b * 256 + c * 65536 + d * 16777216;
		if #blob > 256 * 1024 * 1024 or headLen < 2 or headLen > 1024 * 1024 or 8 + headLen > #blob then return 0, 1 end;

		local ok, head = pcall(function()
			return HttpService:JSONDecode(string.sub(blob, 9, 8 + headLen));
		end);

		if not (ok and type(head) == "table" and type(head.e) == "table") then
			return 0, 1;
		end;

		local list = head.e;
		local at = 8 + headLen;
		local total = #list;
		if total > 2048 then return 0, 1 end;
		local names, expected = {}, 0;
		local crypto = GLOBAL.crypt;
		local binaryHash = false;
		if crypto and type(crypto.hash) == "function" then
			local fine, digest = pcall(crypto.hash, "a\0b", "sha256");
			binaryHash = fine and digest == "59b271ae1bbcb1d31d41929817f4b16fb439eb4f31520b5ad1d5ce98920a7138";
		end;
		Remote.Status.integrity = binaryHash and "sha256" or "structure (executor hash is not binary-safe)";
		for index, entry in ipairs(list) do
			if type(entry) ~= "table" then return 0, 1 end;
			local rel, offset, size = entry[1], entry[2], entry[3];
			if type(rel) ~= "string" or #rel > 512 or rel == "" or rel:find("..", 1, true)
				or rel:find("\\", 1, true) or rel:sub(1, 1) == "/" or rel:find("[%z\1-\31]") or names[rel]
				or type(offset) ~= "number" or offset ~= offset or offset < 0 or offset % 1 ~= 0
				or type(size) ~= "number" or size ~= size or size < 1 or size % 1 ~= 0 or size > 32 * 1024 * 1024
				or offset ~= expected or offset + size > #blob - at then return 0, 1 end;
			if entry[4] ~= nil then
				if type(entry[4]) ~= "string" or #entry[4] ~= 64 or entry[4]:find("[^%da-f]") then return 0, 1 end;
				if binaryHash then
					local fine, digest = pcall(crypto.hash, blob:sub(at + offset + 1, at + offset + size), "sha256");
					if not fine or digest ~= entry[4] then return 0, 1 end;
				end;
			end;
			expected += size;
			names[rel] = true;
			if index % 8 == 0 then
				task.wait();
				if not ALIVE or GLOBAL.__VisualsGeneration ~= INIT_GENERATION then return 0, 1 end;
			end;
		end;
		if expected ~= #blob - at then return 0, 1 end;
		Remote.catalog = Remote.catalog or {};
		for rel in pairs(names) do Remote.catalog[rel] = true end;
		local done, failed, lastPct = 0, 0, 0;

		for index = 1, total do
			if not ALIVE or GLOBAL.__VisualsGeneration ~= INIT_GENERATION then settle(); return done, failed end;
			local entry = list[index];
			local rel, offset, size = entry[1], entry[2], entry[3];
			local body = string.sub(blob, at + offset + 1, at + offset + size);

			local kept;

			if isData(rel) then
				bodies[rel] = body;
				kept = true;
			else
				if not ids[rel] then pendingAssets[rel] = body; retryAfter[rel] = nil end;
				kept = true;
			end;

			if kept then done = done + 1 else failed = failed + 1 end;

			local pct = math.floor(index / total * 10);

			if pct > lastPct then
				lastPct = pct;

				if report then report(index, total) end;

				task.wait();
			end;
		end;

		settle();

		Remote.Status.failed = failed;
		return done, failed;
	end;
	local MEDIA = { png = true, jpg = true, jpeg = true, ogg = true, wav = true, mp3 = true };
	function Remote.registerAll()
		local list = {};
		for rel in pairs(pendingAssets) do
			local ext = string.lower(string.match(rel, "%.(%w+)$") or "");

			if MEDIA[ext] and string.sub(rel, 1, 9) ~= "skyboxes/" then list[#list + 1] = rel end;
		end;
		table.sort(list);
		for _, rel in ipairs(list) do
			if not Remote.current() then return end;
			local finish = Remote.busy();
			pcall(Remote.asset, rel);
			finish();
			task.wait();
		end;
	end;

